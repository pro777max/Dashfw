#include <stdio.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_log.h"
#include "driver/gpio.h"
#include "lvgl.h"
#include "bsp/esp-bsp.h"

static const char *TAG = "DASH_NUCLEAR";

void app_main(void) {
    ESP_LOGI(TAG, "Starting Nuclear Display Test...");

    // 1. ????????????? ??????? ????? BSP (?? ???????? ??????? ??????????? EK79007)
    ESP_LOGI(TAG, "Init Display (EK79007)...");
    bsp_display_start();
    
    // ???? ??????????? 300 ?? ?? ?????? ??????????? ????? ?????? ?????????????
    vTaskDelay(pdMS_TO_TICKS(300));

    // 2. ?????????????? ????????? ????????? ??????? HIGH (??? ???/LEDC)
    ESP_LOGI(TAG, "Forcing backlight GPIO 23 to HIGH...");
    gpio_reset_pin(GPIO_NUM_23);
    gpio_set_direction(GPIO_NUM_23, GPIO_MODE_OUTPUT);
    gpio_set_level(GPIO_NUM_23, 1); // ??????? ??????? ???????

    // 3. ?????? ?????
    bsp_display_lock(0);
    
    lv_obj_t *scr = lv_screen_active();
    
    // ????-??????? ???
    lv_obj_set_style_bg_color(scr, lv_color_hex(0xFF0000), 0);
    lv_obj_set_style_bg_opa(scr, LV_OPA_COVER, 0);
    
    lv_obj_t *label = lv_label_create(scr);
    lv_label_set_text(label, "NUCLEAR\nTEST\nRED\nSCREEN");
    lv_obj_set_style_text_color(label, lv_color_white(), 0);
    lv_obj_set_style_text_font(label, &lv_font_montserrat_14, 0);
    lv_obj_set_style_text_align(label, LV_TEXT_ALIGN_CENTER, 0);
    lv_obj_align(label, LV_ALIGN_CENTER, 0, 0);
    
    // ????????????? ???????? ??? ??????????
    lv_obj_invalidate(scr);
    bsp_display_unlock();
    
    // 4. ?????????? ?????: ?????????????? ??????????? ??????????? ????? ??????
    ESP_LOGI(TAG, "Forcing immediate LVGL redraw...");
    lv_refr_now(NULL);
    
    ESP_LOGI(TAG, "If screen is RED, we won. If black, backlight circuit is gated.");

    // 5. ???? ?????
    int counter = 0;
    while (1) {
        vTaskDelay(pdMS_TO_TICKS(1000));
        counter++;
        if (counter % 5 == 0) {
            ESP_LOGI(TAG, "System Alive... %d sec", counter);
        }
    }
}
