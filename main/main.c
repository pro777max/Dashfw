#include <stdio.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_log.h"
#include "driver/gpio.h"
#include "lvgl.h"
#include "bsp/esp-bsp.h"

static const char *TAG = "DASH_TEST";

void app_main(void) {
    ESP_LOGI(TAG, "Starting Display Test...");

    // ?????????????? ???????
    bsp_display_start();
    
    // ???????? ???????? ????????? ????? BSP (????? ?? ????????? ??-?? ?????????)
    bsp_display_brightness_set(100); 
    ESP_LOGI(TAG, "Attempted BSP backlight control");
    
    // ????????? ???????: ????????? GPIO 26 ????????
    ESP_LOGI(TAG, "Trying direct GPIO 26 control for backlight...");
    gpio_reset_pin(GPIO_NUM_26);
    gpio_set_direction(GPIO_NUM_26, GPIO_MODE_OUTPUT);
    gpio_set_level(GPIO_NUM_26, 1); // HIGH = ????????? ????????
    ESP_LOGI(TAG, "GPIO 26 set to HIGH");

    bsp_display_lock(0);
    
    // ???????? ???????? ?????
    lv_obj_t *scr = lv_screen_active();
    
    // ????: ??????? ??? ?? ???? ?????
    lv_obj_set_style_bg_color(scr, lv_color_hex(0xFF0000), 0);
    lv_obj_set_style_bg_opa(scr, LV_OPA_COVER, 0);
    
    // ????: ??????? ????? ????? ? ??????
    lv_obj_t *label = lv_label_create(scr);
    lv_label_set_text(label, "DISPLAY TEST\n1024x600\nRED SCREEN");
    lv_obj_set_style_text_color(label, lv_color_white(), 0);
    lv_obj_set_style_text_font(label, &lv_font_montserrat_14, 0);
    lv_obj_set_style_text_align(label, LV_TEXT_ALIGN_CENTER, 0);
    lv_obj_align(label, LV_ALIGN_CENTER, 0, 0);
    
    bsp_display_unlock();
    ESP_LOGI(TAG, "Test UI created");

    while (1) {
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
}
